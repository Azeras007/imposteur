import type { WordPack, WordPair } from '../types';

/** "poêle|casserole" -> { id, a, b } */
function pairs(packId: string, list: string[]): WordPair[] {
  return list.map((line, i) => {
    const [a, b] = line.split('|').map((s) => s.trim());
    return { id: `${packId}-${i}`, a, b };
  });
}

function pack(
  id: string,
  emoji: string,
  name: string,
  list: string[],
  adult = false,
): WordPack {
  return { id, name, emoji, builtin: true, adult, pairs: pairs(id, list) };
}

